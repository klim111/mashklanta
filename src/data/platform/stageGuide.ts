/** הכלים של השלב לסיור — החיוניים קודם, ואחריהם האופציונליים */
export function stageGuideTools(stage: PlanStageId): PlatformTool[] {
  const { essential, optional } = PLAN_STAGE_TOOLS[stage];
  const seen = new Set<string>();
  return toolsByIds([...essential, ...optional]).filter((tool) => {
    if (seen.has(tool.id)) return false;
    seen.add(tool.id);
    return true;
  });
}
