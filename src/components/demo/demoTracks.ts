/**
 * ה"סרטונים" של הפלטפורמה.
 *
 * כל מסלול הוא רצף סצנות, וכל סצנה היא מסך אמיתי מהמערכת עם ההסבר שמלווה
 * אותו. אותו מסך יכול להופיע בכמה סצנות עם דגש אחר — בדיוק כמו בסרטון הדגמה,
 * שבו המצלמה נשארת על המסך בזמן שמסבירים מה רואים בו.
 */

export interface DemoScene {
  id: string;
  screen: DemoScreenId;
  /** הכותרת שמופיעה לצד המסך */
  title: string;
  /** השורה שמתחת לכותרת */
  subtitle: string;
  /** מה שרואים במסך — שלוש נקודות לכל היותר */
  points: string[];
  /** תגית קטנה מעל הכותרת (למשל: «שלב 2 מתוך 5») */
  badge?: string;
  /** כמה זמן הסצנה נשארת על המסך */
  ms?: number;
}

export interface DemoTrack {
  id: 'undecided' | 'new-mortgage' | 'refinance';
  label: string;
  hint: string;
  icon: LucideIcon;
  gradient: string;
  /** הכיתוב בתוך נגן ההדגמה */
  title: string;
  scenes: DemoScene[];
}

