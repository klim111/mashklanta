export function trackById(id: DemoTrack['id']): DemoTrack {
  const found = DEMO_TRACKS.find((track) => track.id === id);
  if (!found) throw new Error(`unknown demo track: ${id}`);
  return found;
}

export function sceneDuration(scene: DemoScene): number {
  return scene.ms ?? SCENE_MS;
}
